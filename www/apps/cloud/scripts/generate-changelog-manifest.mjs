import { mkdir, readdir, writeFile } from "fs/promises"
import path from "path"

const CHANGELOG_DIR = path.join(process.cwd(), "generated", "changelog")
const MANIFEST_NAME = "index.mjs"
const ENTRY_FILE_REGEX = /^(\d{4}-\d{2}-\d{2})\.mjs$/

/**
 * Generates `generated/changelog/index.mjs` from the entry files in
 * `generated/changelog`. The manifest only holds each entry's date and a lazy
 * `import()` of its file, so consumers (the changelog page and the public
 * `/api/changelog` endpoint) load the entries of the requested page only,
 * rather than the whole changelog. Bundlers code-split each `import()` into its
 * own chunk, so the manifest's size stays constant as entries are added.
 */
export async function generateChangelogManifest() {
  await mkdir(CHANGELOG_DIR, { recursive: true })

  const files = await readdir(CHANGELOG_DIR)

  // File names are `YYYY-MM-DD.mjs`, so a reverse lexicographic sort puts the
  // newest entry first.
  const dates = files
    .map((file) => ENTRY_FILE_REGEX.exec(file)?.[1])
    .filter(Boolean)
    .sort()
    .reverse()

  const content = `// This file is generated by \`scripts/generate-changelog-manifest.mjs\`.
// Don't edit it manually. Add a \`YYYY-MM-DD.mjs\` entry file to this directory
// instead, then run \`yarn prep\` in \`www/apps/cloud\`.

/** @type {{ date: string, load: () => Promise<{ default: import("../../utils/changelog").ChangelogEntry }> }[]} */
export const changelogEntries = [
${dates.map((date) => `  { date: "${date}", load: () => import("./${date}.mjs") },`).join("\n")}
]
`

  await writeFile(path.join(CHANGELOG_DIR, MANIFEST_NAME), content, "utf-8")

  return dates.length
}

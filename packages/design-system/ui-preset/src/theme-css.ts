import {
  ANIMATION,
  BORDER_RADIUS,
  FONT_FAMILY_MONO,
  FONT_FAMILY_SANS,
  KEYFRAMES,
  TRANSITION_PROPERTY_FG,
} from "./constants"
import { theme } from "./theme/extension/theme"
import { colors } from "./theme/tokens/colors"
import { components } from "./theme/tokens/components"
import { effects } from "./theme/tokens/effects"
import { typography } from "./theme/tokens/typography"

type NestedTokens = { [key: string]: string | NestedTokens }
type Declarations = Record<string, string | number>

const DARK_SELECTORS = [".dark", '[data-mode="dark"]']

const toKebabCase = (value: string) =>
  value.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`)

const flattenTokens = (
  tokens: NestedTokens,
  prefix: string[] = []
): [string, string][] =>
  Object.entries(tokens).flatMap(([key, value]) => {
    const path = key === "DEFAULT" ? prefix : [...prefix, key]

    return typeof value === "string"
      ? [[path.join("-"), value] as [string, string]]
      : flattenTokens(value, path)
  })

const declarations = (values: Declarations, indent = "  ") =>
  Object.entries(values)
    .map(([property, value]) => {
      const name = property.startsWith("--") ? property : toKebabCase(property)
      return `${indent}${name}: ${value};`
    })
    .join("\n")

const rule = (selector: string, values: Declarations, indent = "  ") =>
  `${indent}${selector} {\n${declarations(values, `${indent}  `)}\n${indent}}`

const keyframes = (indent: string) =>
  Object.entries(KEYFRAMES)
    .map(
      ([name, steps]) =>
        `${indent}@keyframes ${name} {\n${Object.entries(steps)
          .map(([step, values]) => rule(step, values, `${indent}  `))
          .join("\n")}\n${indent}}`
    )
    .join("\n")

/**
 * Builds the CSS-first Tailwind CSS 4 version of the preset from the same
 * tokens as the JavaScript preset.
 */
export function generateThemeCSS() {
  const themeVariables: Declarations = {
    ...Object.fromEntries(
      flattenTokens(theme.extend.colors).map(([name, value]) => [
        `--color-${name}`,
        value,
      ])
    ),
    ...Object.fromEntries(
      flattenTokens(theme.extend.boxShadow).map(([name, value]) => [
        `--shadow-${name}`,
        value,
      ])
    ),
    ...Object.fromEntries(
      Object.entries(BORDER_RADIUS).map(([name, value]) => [
        `--radius-${name}`,
        value,
      ])
    ),
    "--font-sans": FONT_FAMILY_SANS.join(", "),
    "--font-mono": FONT_FAMILY_MONO.join(", "),
    ...Object.fromEntries(
      Object.entries(ANIMATION).map(([name, value]) => [
        `--animate-${name}`,
        value,
      ])
    ),
  }

  const darkComponents = Object.entries(
    components.dark as Record<string, Declarations>
  ).map(([selector, values]) =>
    rule(DARK_SELECTORS.map((dark) => `${dark} ${selector}`).join(", "), values)
  )

  const base = [
    rule("*", { borderColor: "var(--border-base)" }),
    rule('button:not(:disabled), [role="button"]:not(:disabled)', {
      cursor: "pointer",
    }),
    rule(":root", { ...colors.light, ...effects.light }),
    ...Object.entries(components.light as Record<string, Declarations>).map(
      ([selector, values]) => rule(selector, values)
    ),
    rule(DARK_SELECTORS.join(", "), { ...colors.dark, ...effects.dark }),
    ...darkComponents,
  ]

  const utilities = [
    `@utility transition-fg {\n${declarations({
      transitionProperty: TRANSITION_PROPERTY_FG,
      transitionTimingFunction:
        "var(--tw-ease, var(--default-transition-timing-function))",
      transitionDuration:
        "var(--tw-duration, var(--default-transition-duration))",
    })}\n}`,
    ...Object.entries(typography as Record<string, Declarations>).map(
      ([selector, values]) =>
        `@utility ${selector.replace(/^\./, "")} {\n${declarations(values)}\n}`
    ),
  ]

  const darkVariant = DARK_SELECTORS.flatMap((dark) => [
    dark,
    `${dark} *`,
  ]).join(", ")

  return (
    [
      "/* Generated by @medusajs/ui-preset. Do not edit. */",
      '@import "tw-animate-css";',
      `@custom-variant dark (&:where(${darkVariant}));`,
      `@theme inline {\n${declarations(themeVariables)}\n${keyframes("  ")}\n}`,
      `@layer base {\n${base.join("\n")}\n}`,
      ...utilities,
    ].join("\n\n") + "\n"
  )
}
